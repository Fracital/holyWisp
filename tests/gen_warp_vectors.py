#!/usr/bin/env python3
"""Write tests/warp_vectors.h from the edge router's own code, so that test_warp checks holyWisp's
tunnel choice against the router's and not against a copy of it.

    python3 tests/gen_warp_vectors.py [path/to/edge-router.py] > tests/warp_vectors.h && make format

The router is abulxt's deploy/edge-wisp/edge-router.py (default: ../abulxt next to this repo).
It is only imported, never run. Regenerate when the router's site_key, rendezvous_score or
WarpTunnels.pick changes; holyWisp must change with it, or a site's UDP leaves from another exit
than its TCP. The same vectors as JSON, for the router's tests: --json.
"""

import importlib.util
import json
import os
import socket
import sys

HOSTS = [
    "example.com", "www.example.com", "WWW.Example.COM.", "a.b.c.example.com", "example.co.uk",
    "www.bbc.co.uk", "x.y.z.gov.uk", "sub.example.com.au", "foo.ac.jp", "a.co.co", "co.uk", "x.CO.UK",
    "t.co", "a.t.co", "discord.gg", "cdn.discordapp.com", "web.whatsapp.com", "rr3---sn-a.googlevideo.com",
    "deep.a.b.gob.mx", "a.ltd.uk", "a.b.museum", "localhost", "com", "", ".", "a..b.com", ".com",
    "trailing.dots.example.org...", "1.2.3.4.example", "x.ne.jp", "a.b.c.d.e.f.g.h.i.j", "a.verylongtld.xx",
    "a.b.xyz", "a.or.kr", "a.go.id", "a.nic.in", "a.mil.br", "a.plc.uk", "a.edu.au", "a.com.cn",
]

LITERAL_KEYS = ["1.1.1.1", "104.28.219.137", "2606:4700:4700::1111", "2a09:bac5:4e23:2e3c::49b:2f"]

TUNNEL_SETS = [
    ["warp0", "warp1", "warp2", "warp3"],
    ["warp0", "warp2", "warp3"],
    ["warp1"],
    ["wg-a", "wg_b", "w.c", "warp10", "warp11", "warp12", "warp13", "warp14"],
]


def load_router(path):
    spec = importlib.util.spec_from_file_location("edge_router", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    args = [a for a in sys.argv[1:] if a != "--json"]
    here = os.path.dirname(os.path.abspath(__file__))
    path = args[0] if args else os.path.join(here, "..", "..", "abulxt", "deploy", "edge-wisp", "edge-router.py")
    r = load_router(path)

    sites = [(h, r.site_key(h)) for h in HOSTS]
    keys = sorted(set(k for _, k in sites) | set(LITERAL_KEYS))
    names = sorted(set(n for t in TUNNEL_SETS for n in t))
    scores = [(k, n, r.rendezvous_score(k, n)) for k in keys for n in names]
    picks = []
    for ti, tunnels in enumerate(TUNNEL_SETS):
        wt = r.WarpTunnels([r.WarpTunnel(n, 0x7701 + i) for i, n in enumerate(tunnels)])
        for n in tunnels:
            wt.up[(n, socket.AF_INET)] = True
        for k in keys:
            picks.append((ti, k, wt.pick(k, socket.AF_INET).name))

    if "--json" in sys.argv[1:]:
        json.dump({"site_key": sites, "score": scores, "tunnel_sets": TUNNEL_SETS, "pick": picks},
                  sys.stdout, indent=1)
        print()
        return

    out = ["/* Generated by tests/gen_warp_vectors.py from edge-router.py. Do not edit. */", ""]
    out.append("static const struct { const char *host, *key; } WARP_SITE_VECTORS[] = {")
    out += ["\t{%s, %s}," % (c_string(h), c_string(k)) for h, k in sites]
    out += ["};", ""]
    out.append("static const struct { const char *key, *name; uint64_t score; } WARP_SCORE_VECTORS[] = {")
    out += ["\t{%s, %s, 0x%016xULL}," % (c_string(k), c_string(n), s) for k, n, s in scores]
    out += ["};", ""]
    out.append("static const char *const WARP_TUNNEL_SETS[][%d] = {" % (max(len(t) for t in TUNNEL_SETS) + 1))
    out += ["\t{%s, NULL}," % ", ".join(c_string(n) for n in t) for t in TUNNEL_SETS]
    out += ["};", ""]
    out.append("static const struct { int set; const char *key, *name; } WARP_PICK_VECTORS[] = {")
    out += ["\t{%d, %s, %s}," % (ti, c_string(k), c_string(n)) for ti, k, n in picks]
    out += ["};"]
    print("\n".join(out))


if __name__ == "__main__":
    main()
